r"""Generate taxonomy_tree.tex (TikZ standalone) for the CSUR draft from coding.csv, so counts cannot drift.

Differences from ../../taxonomy_coding_v2_2026-11-07/figure/gen_tree.py:
  * rows restricted to final_decision starting with 'include' (N = 95, as in stats_final95.json);
  * leaves follow outline.md v1: learned stops of branch B merged into 5.1, C risk budget merged into 6.2,
    empty leverage leaf dropped (leverage is never the primary RL-sized object after full-text coding);
  * section numbers follow the CSUR skeleton (main.tex): A=4.1, B=4.2, C=4.3, D=4.4, evaluation 5, challenges 6 (v0.11);
  * fonts: \small leaves / \footnotesize notes, so at native size the smallest text is 8 pt = 0.8 x 10 pt body.
v0.8: reads coding_v0.8.csv; branch descriptions follow the v0.8 assignment rule.
Usage: python3 -I gen_tree.py && pdflatex taxonomy_tree.tex   (run inside figure/)
"""
import csv, collections
rows = [r for r in csv.DictReader(open('../coding_v0.8.csv'))
        if r['final_decision'].startswith('include')]
N = len(rows)
br = collections.Counter(r['taxonomy_branch'][0] for r in rows)
lf = collections.Counter((r['taxonomy_branch'][0], r['taxonomy_leaf']) for r in rows)
imp_sq = sum(1 for r in rows if r['taxonomy_leaf'] == 'share quantity (±k)' and r['sizing_type'] == 'implicit')
hyb = sum(1 for r in rows if r['taxonomy_branch'][0] == 'C' and r['rl_hybrid'] == 'y')
L = lambda b, *names: sum(lf[(b, n)] for n in names)
TREE = [
 ('A', 'Predict-then-size', 'a model fitted to a prediction target feeds a fixed sizing rule', '4.1', [
   ('Kelly and growth-optimal fractions', L('A', 'Kelly/growth'), '4.1.1'),
   ('Risk parity and risk budgeting, incl.\\ hierarchical risk parity', L('A', 'risk parity'), '4.1.2'),
   (f"Mean-variance ({L('A','mean-variance')}) and volatility targeting ({L('A','volatility targeting')})", L('A', 'mean-variance', 'volatility targeting'), '4.1.3'),
   (f"Forecast-to-size and cash rules ({L('A','rule+ML forecast')}) and learned stops ({L('A','stop/take-profit rule')})", L('A', 'rule+ML forecast', 'stop/take-profit rule'), '4.1.4')]),
 ('B', 'Learn-to-size', 'the size-producing model is fitted directly to a trading or utility objective', '4.2', [
   (f"Models trained on a trading objective, incl.\\ learned stops ({L('B','stop/take-profit level')})", L('B', 'end-to-end / rule-base network', 'stop/take-profit level'), '4.2.1'),
   ('Deep stochastic-control solvers', L('B', 'deep stochastic-control solver'), '4.2.2')]),
 ('C', 'Size as an RL action', 'the size is part of an action learned from rewards', '4.3', [
   (f"Share quantity $\\pm k$ ({imp_sq} implicit)", L('C', 'share quantity (±k)'), '4.3.1'),
   (f"Portfolio weights incl.\\ cash, cash ratio, risk budget", L('C', 'weights incl. cash / cash ratio', 'risk budget', 'leverage / margin'), '4.3.2'),
   ('Position fraction in one asset', L('C', 'position fraction'), '4.3.3'),
   ('Stop-loss and take-profit levels', L('C', 'stop/take-profit level'), '4.3.4')]),
 ('D', 'Size set by a language model', 'a prompted language model outputs a risk budget or a long-short ratio', '4.4', [])]
out = [r"""% AUTO-GENERATED by gen_tree.py from coding.csv (final_decision = include) -- edit the generator, not this file.
\documentclass[border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage[scaled=0.92]{helvet}
\usepackage{tikz}
\renewcommand{\familydefault}{\sfdefault}
\begin{document}
\begin{tikzpicture}[font=\small,
  rootn/.style={draw, thick, fill=black!8, rounded corners=2pt, inner sep=4pt, anchor=north west, align=left},
  brn/.style={draw, fill=black!4, rounded corners=2pt, inner sep=3pt, anchor=west, text width=10.6cm},
  lfn/.style={anchor=west, inner sep=1.5pt, text width=10.0cm},
  ln/.style={black!60, line width=0.5pt}]
""", r"\node[rootn] (root) at (0,0) {\textbf{Machine-learned position sizing}\quad $N=%d$ studies\\ \footnotesize How the model determines position size};" % N]
y = -1.45; brs = []
for code, name, desc, sec, leaves in TREE:
    out.append(r"\node[brn] (%s) at (0.7,%.2f) {\textbf{%s\; %s} \hfill %d \quad Sec.~%s\\[-1pt] \footnotesize %s};" % (code, y, code, name, br[code], sec, desc))
    brs.append(code); y -= 0.86
    for i, (t, n, s) in enumerate(leaves):
        out.append(r"\node[lfn] (%s%d) at (1.5,%.2f) {%s \hfill %d \quad Sec.~%s};" % (code, i, y, t, n, s))
        out.append(r"\draw[ln] ([xshift=0.35cm]%s.south west) |- (%s%d.west);" % (code, code, i))
        y -= 0.52
    y -= 0.34
for c in brs:
    out.append(r"\draw[ln] (0.35,-0.85) |- (%s.west);" % c)
out.append(r"\node[anchor=west, text=black!65, font=\footnotesize] at (0.7,%.2f) {Across all %d studies: Sec.~5 evaluation practice $\cdot$ Sec.~6 open challenges and reporting protocol};" % (y + 0.05, N))
out.append(r"\end{tikzpicture}" + "\n" + r"\end{document}")
open('taxonomy_tree.tex', 'w').write('\n'.join(out) + '\n')
assert N == 95, N
assert sum(br.values()) == N and sum(n for *_, lv in TREE for _, n, _ in lv) + br['D'] == N
print('ok N=%d' % N, dict(br), 'implicit share-quantity', imp_sq, 'C rule layer', hyb)
